# Create a function to get poem by title
def get_poem_by_title(title):
    """Find and return a poem by its title"""
    all_poems = get_all_poems()
    for poem in all_poems:
        if poem["title"] == title:
            return poem
    return None

# Create a function to get poems by grade
def get_poems_by_grade(grade):
    """Return poems filtered by grade"""
    all_poems = get_all_poems()
    return [poem for poem in all_poems if poem["grade"] == grade]

